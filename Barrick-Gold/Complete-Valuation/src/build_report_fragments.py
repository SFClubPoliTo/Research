"""Write the numbers and figure names both report editions read.

One generated file, ``results_20261024.tex``, is written identically into
``outputs/report_paper/sections/generated/`` and
``outputs/report_unificato/chapters/generated/`` so the two editions cannot
quote different results.  Figures are copied into the shared
``outputs/img/publication`` store under content-hashed names.  Inputs are the
dated, carry-consistent outputs of ``build_dated_paper_audit.py``.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil

import numpy as np
import pandas as pd

R = next(p for p in Path(__file__).resolve().parents if (p / "pyproject.toml").is_file())
A = R / "outputs/paper_audit_20261024"
FIG = R / "outputs/img/paper_audit_20261024"
PUB = R / "outputs/img/publication"
MODELS = ("black_scholes", "heston", "bates_poisson", "full_bates_hawkes")
TAG = {"black_scholes": "BS", "heston": "H", "bates_poisson": "B", "full_bates_hawkes": "W"}
OOS_TAG = {"bs": "BS", "heston": "H", "bates": "B", "hawkes": "W"}


def publish(path: Path) -> str:
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    name = f"{digest}_{path.name}"
    target = PUB / name
    if not target.exists():
        shutil.copyfile(path, target)
    return f"../img/publication/{name}"


def fmt(value: float, digits: int = 2) -> str:
    return f"{value:,.{digits}f}"


def main() -> None:
    lines = ["% Generated by src/build_report_fragments.py from outputs/paper_audit_20261024.",
             "% Do not edit by hand; rerun the generator after rebuilding the evidence."]

    def macro(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    cal = pd.read_csv(A / "calibration_summary_audited.csv").set_index("model")
    audit = json.loads((A / "calibration_audit.json").read_text())
    legacy = pd.read_csv(R / "outputs/paper_audit/calibration_summary_audited.csv").set_index("model")
    legacy = legacy.rename(index={"bates": "bates_poisson"})
    for m in MODELS:
        macro(f"Cal{TAG[m]}IVRMSE", fmt(cal.loc[m, "iv_rmse_bp"]))
        macro(f"Cal{TAG[m]}IVRMSELegacy", fmt(legacy.loc[m, "iv_rmse_bp"]))
    params = {m: json.loads((R / f"data/processed/team8/calibration_q040_audited_20261024/"
                                 f"{ {'bates_poisson': 'bates'}.get(m, m)}.json").read_text())["parameters"]
              for m in MODELS}
    w = params["full_bates_hawkes"]
    macro("HawkesBranching", fmt(w["branching_ratio"], 3))
    macro("HawkesBeta", fmt(w["beta"], 2))
    macro("HawkesHalfLifeDays", fmt(np.log(2) / w["beta"] * 365.25, 1))
    macro("HawkesMeanIntensity", fmt(w["lambda_bar"] / (1 - w["branching_ratio"]), 2))
    macro("BatesLambda", fmt(params["bates_poisson"]["lambd"], 2))
    macro("HestonKappa", fmt(params["heston"]["kappa"], 2))
    macro("FellerRelaxedLossRatio", fmt(100 * (1 - audit["feller_relaxed_heston"]["loss_ratio_to_constrained"]), 0))
    profile = pd.read_csv(A / "heston_kappa_profile.csv")
    flat = profile[profile.loss_ratio_to_optimum <= 1.03].kappa
    macro("KappaFlatLow", fmt(flat.min(), 0))
    macro("KappaFlatHigh", fmt(flat.max(), 0))
    carry = pd.read_csv(A / "carry_sensitivity.csv").set_index("dividend_yield")
    macro("CarryPriceRMSEZero", fmt(carry.loc[0.0, "heston_price_rmse_usd"]))
    macro("CarryPriceRMSEFee", fmt(carry.loc[0.004, "heston_price_rmse_usd"]))
    futures = pd.read_csv(A / "carry_futures_implied.csv")
    liquid = futures[futures.maturity_years >= 0.45]
    macro("FuturesYieldLow", fmt(100 * liquid.implied_gld_yield.min()))
    macro("FuturesYieldHigh", fmt(100 * liquid.implied_gld_yield.max()))
    macro("AmericanPremiumMax", f"{json.loads((A / 'american_check.json').read_text())['max_premium_usd']:.1e}")

    proxy = pd.read_csv(A / "proxy_summary.csv").set_index("model")
    for m in MODELS:
        t = TAG[m]
        macro(f"Val{t}Median", fmt(proxy.loc[m, "median_bn"]))
        macro(f"Val{t}PTen", fmt(proxy.loc[m, "p10_bn"]))
        macro(f"Val{t}PNinety", fmt(proxy.loc[m, "p90_bn"]))
        macro(f"Val{t}Mean", fmt(proxy.loc[m, "mean_bn"]))
        macro(f"Val{t}Negative", fmt(100 * proxy.loc[m, "negative_fraction"], 1))
        macro(f"Val{t}Explicit", fmt(proxy.loc[m, "five_year_median_bn"]))
        macro(f"Val{t}ExplicitRiskFree", fmt(proxy.loc[m, "explicit_risk_free_median_bn"]))
    for m in MODELS:
        macro(f"Bar{TAG[m]}", fmt(40.0 * proxy.loc[m, "median_bn"] / proxy.median_bn.max()))
    macro("ValMedianLow", fmt(proxy.median_bn.min()))
    macro("ValMedianHigh", fmt(proxy.median_bn.max()))
    macro("ValExplicitLow", fmt(proxy.five_year_median_bn.min()))
    macro("ValExplicitHigh", fmt(proxy.five_year_median_bn.max()))
    macro("ValPNinetyLow", fmt(proxy.p90_bn.min()))
    macro("ValPNinetyHigh", fmt(proxy.p90_bn.max()))
    macro("TerminalShare", fmt(100 * proxy.terminal_share_of_mean.mean(), 0))
    sens = pd.read_csv(A / "numerical_sensitivity.csv")
    macro("NumericalMedianLow", fmt(sens.median_bn.min()))
    macro("NumericalMedianHigh", fmt(sens.median_bn.max()))
    hawkes = sens[sens.model == "full_bates_hawkes"]
    macro("NumericalHawkesLow", fmt(hawkes.median_bn.min()))
    macro("NumericalHawkesHigh", fmt(hawkes.median_bn.max()))
    attribution = pd.read_csv(A / "correction_attribution.csv")
    steps = list(dict.fromkeys(attribution.step))
    for index, label in enumerate(("Legacy", "Clock", "Anchor", "Carry")):
        for m in MODELS:
            value = attribution[(attribution.model == m) & (attribution.step == steps[index])].median_bn.iloc[0]
            macro(f"Att{label}{TAG[m]}", fmt(value))
    copper = pd.read_csv(A / "copper_paired_summary.csv")
    primary = copper[(copper.scope == "explicit_flows_primary") & (copper.terminal_score_rho == 0)].set_index("model")
    for m in MODELS:
        t = TAG[m]
        macro(f"Cu{t}Gold", fmt(primary.loc[m, "gold_only_mean_bn"], 3))
        macro(f"Cu{t}Combined", fmt(primary.loc[m, "gold_plus_copper_mean_bn"], 3))
        macro(f"Cu{t}Delta", fmt(primary.loc[m, "copper_increment_mean_bn"], 3))
        macro(f"Cu{t}SE", fmt(primary.loc[m, "copper_increment_se_mn"], 1))
    macro("CuDeltaLow", fmt(primary.copper_increment_mean_bn.min()))
    macro("CuDeltaHigh", fmt(primary.copper_increment_mean_bn.max()))

    # Terminal discount rate on the dated clock (rate in effect at the horizon).
    import sys
    from dataclasses import replace
    from scipy.stats import binomtest
    sys.path.insert(0, str(R / "src"))
    from barrick_unified.dated_valuation import build_schedule, wacc_paths
    from barrick_unified.multimodel_valuation import load_multimodel_inputs
    cfg = json.loads((R / "data/processed/config/paper_dated_q040_20261024.json").read_text(encoding="utf-8"))
    inputs, _ = load_multimodel_inputs(R, cfg)
    base = json.loads((R / cfg["base_valuation_config"]).read_text(encoding="utf-8"))
    clock = cfg["valuation_clock"]
    schedule = build_schedule(clock["valuation_date"], clock["horizon_end"], clock["first_operating_quarter"],
                              base["model"]["operating_vector_status"])
    shocks = np.random.default_rng(int(cfg["simulation"]["wacc_seed"])).standard_normal(
        (int(cfg["simulation"]["n_simulations"]), schedule.rate_years - 1))
    rates = wacc_paths(inputs, shocks, schedule.rate_years)
    terminal = float(np.median(rates[:, -1]))
    g, roic = inputs.stable_growth, inputs.roic_stable
    macro("TerminalWACC", fmt(100 * terminal, 3))
    macro("TerminalMultiple", fmt((1 + g) * (1 - g / roic) / (terminal - g)))
    floor, cap = g + inputs.terminal_spread_floor, 0.25
    macro("WACCClippedShare", fmt(100 * float(np.mean((rates <= floor + 1e-12) | (rates >= cap - 1e-12))), 2))
    macro("HorizonYears", fmt(schedule.horizon_years))
    macro("StubDays", str(int(schedule.quarters[0].days_remaining)))

    # Physical one-session gold intervals (frozen 11 October panel, q = 0 option fits).
    physical = json.loads((R / "outputs/physical_measure/20261011-four-model-gold-complete/summary.json").read_text())
    rows = []
    for name, t in (("gbm", "BS"), ("heston", "H"), ("bates", "B"), ("full_bates_hawkes", "W")):
        stats = physical["models"][name]
        n = int(stats["matched"])
        for level in (95, 80):
            hits = int(round(stats[f"coverage{level}"] * n))
            p = binomtest(hits, n, level / 100).pvalue
            macro(f"Cov{t}{'NinetyFive' if level == 95 else 'Eighty'}", f"{hits}/{n}")
            macro(f"Cov{t}{'NinetyFive' if level == 95 else 'Eighty'}P", fmt(p, 3))
            rows.append({"model": name, "nominal": level / 100, "hits": hits, "targets": n, "binomial_p": p})
    pd.DataFrame(rows).to_csv(A / "physical_coverage_tests.csv", index=False)

    oos = A / "oos_audit.csv"
    if oos.exists():
        table = pd.read_csv(oos)
        new = table[table.run.str.startswith("q040")]
        tests = pd.read_csv(A / "oos_dm_tests.csv")
        tests = tests[tests.run.str.startswith("q040")].set_index("comparison")
        for model, t in OOS_TAG.items():
            mean = new[(new.model == model) & (new.benchmark == "mean")].iloc[0]
            pers = new[(new.model == model) & (new.benchmark == "persistence")].iloc[0]
            macro(f"Oos{t}RMSE", fmt(mean.mean_daily_rmse_bp))
            macro(f"Oos{t}RMean", fmt(100 * mean.r2))
            macro(f"Oos{t}RPersistence", fmt(100 * pers.r2))
            macro(f"Oos{t}BeatsPersistence", str(int(pers.dates_model_beats_benchmark)))
            macro(f"Oos{t}DMPersistenceP", fmt(tests.loc[f"{model} vs persistence", "p_value_two_sided"], 3))
        for other, t in (("bs", "BS"), ("heston", "H"), ("bates", "B")):
            macro(f"OosDMHawkesVs{t}P", fmt(tests.loc[f"hawkes vs {other}", "p_value_two_sided"], 3))
        macro("OosDates", str(int(new.dates.max())))
        macro("OosObservations", fmt(new[new.benchmark == "mean"].observations.max(), 0))
        macro("OosPersistenceObservations", fmt(new[new.benchmark == "persistence"].observations.max(), 0))
        macro("OosPersistenceRMSE", fmt(new[new.benchmark == "persistence"].benchmark_mean_daily_rmse_bp.iloc[0]))
        macro("FigOosRmse", publish(FIG / "oos_rmse.png"))
        macro("FigOosRsquared", publish(FIG / "oos_r2.png"))

    for name in ("fig_val_primary.png", "fig_val_multi.png", "fig_terminal_share.png", "fig_correction_attribution.png",
                 "black_scholes_residual_heatmap.png", "heston_residual_heatmap.png", "bates_residual_heatmap.png",
                 "bates_hawkes_residual_heatmap.png"):
        stem = "".join(part.title() for part in name.split(".")[0].split("_"))
        macro("Fig" + stem, publish(FIG / name))
    silver = R / "outputs/thesis/20261024-unificato-gph-unclipped/team7_empirical/arfima_fd_silver.png"
    if silver.exists():
        macro("FigArfimaFdSilver", publish(silver))
        gph = json.loads((silver.parent / "figure_manifest.json").read_text())["gph_d"]
        macro("GphGoldAbs", fmt(gph["gold"], 3))
        macro("GphSilverAbs", fmt(gph["silver"], 3))

    if oos.exists():
        # Article 8 reads the same corrected-run OOS numbers through its draft hook.
        run = pd.read_csv(R / "data/processed/team8/oos_q040_20261024/rolling/model_summary.csv").set_index("model")
        art8 = ["% Generated by Complete-Valuation/src/build_report_fragments.py from the",
                "% corrected rolling run data/processed/team8/oos_q040_20261024 (q = 0.40%, equal search).",
                "\\newcommand{\\OOSHookCheck}{}",
                f"\\newcommand{{\\OOSForecastOrigins}}{{{int(run.forecast_origins.max())}}}",
                f"\\newcommand{{\\OOSCommonTargetObservations}}{{{int(run.common_target_observations.min())}}}",
                f"\\newcommand{{\\OOSPersistenceTargetObservations}}{{{int(run.persistence_common_observations.min())}}}"]
        dm = pd.read_csv(A / "oos_dm_tests.csv")
        dm = dm[dm.run.str.startswith("q040")].set_index("comparison")
        for model, t in OOS_TAG.items():
            tag = {"BS": "BS", "H": "H", "B": "B", "W": "W"}[t]
            art8.append(f"\\newcommand{{\\OOSRTwoPersist{tag}}}{{{100 * run.loc[model, 'r2_oos_vs_persistence_date_equal']:.2f}\\%}}")
            art8.append(f"\\newcommand{{\\OOSDMPersist{tag}}}{{{dm.loc[f'{model} vs persistence', 'dm_stat']:.2f}}}")
        beats = table[(table.run.str.startswith("q040")) & (table.model == "hawkes") & (table.benchmark == "persistence")]
        art8.append(f"\\newcommand{{\\OOSHawkesDatesBeatPersist}}{{{int(beats.dates_model_beats_benchmark.iloc[0])}}}")
        target = R.parent / "Gold-Options-Stochastic-Modeling/img/diagnostics_ibkr"
        if target.is_dir():
            (target / "oos_article_numbers.tex").write_text("\n".join(art8) + "\n", encoding="utf-8")
            for name in ("oos_table_rows.tex", "online_welch_goyal_cumulative.png"):
                shutil.copyfile(R / "outputs/img/oos_q040_20261024" / name, target / name)

    text = "\n".join(lines) + "\n"
    for target in (R / "outputs/report_paper/sections/generated", R / "outputs/report_unificato/chapters/generated"):
        target.mkdir(parents=True, exist_ok=True)
        (target / "results_20261024.tex").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
